import { createRequire } from 'node:module';
import { spawn, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import net from 'node:net';
import assert from 'node:assert/strict';

const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const runtime=mkdtempSync(resolve(tmpdir(),'editorial-browser-'));
const evidence=resolve(root,'evidence/browser');mkdirSync(evidence,{recursive:true});
const php=process.env.PHP_BIN||'php';
const port=await new Promise((resolvePort,reject)=>{const s=net.createServer();s.on('error',reject);s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolvePort(p));});});
const origin=`http://localhost:${port}`;
const fixture=spawnSync(php,['tests/browser_fixture.php',runtime,origin],{cwd:root,encoding:'utf8'});
if(fixture.status!==0)throw new Error(fixture.stderr+fixture.stdout);
const state=JSON.parse(readFileSync(resolve(runtime,'fixture.json'),'utf8'));
// Without workers the server is one process, so stopping it stops all of it.
const server=spawn(php,['-S',`localhost:${port}`,'-t','public','public/router.php'],{cwd:root,env:{...process.env,...state.env,PHP_CLI_SERVER_WORKERS:undefined},stdio:['ignore','ignore','pipe']});
let serverErrors='';server.stderr.on('data',data=>{serverErrors+=data.toString();});
let browser;
const checks=[];const pageErrors=[];const completePosts=[];
const check=(value,message)=>{assert.ok(value,message);checks.push(message);};
try {
  for(let i=0;i<100;i++){try{if((await fetch(origin+'/login')).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1100}});
  const page=await context.newPage();page.on('pageerror',e=>pageErrors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST'&&/\/approval\/apr_[a-f0-9]{32}\/complete$/.test(new URL(r.url()).pathname))completePosts.push(r.url());});
  const cdp=await context.newCDPSession(page);
  await cdp.send('WebAuthn.enable');
  await cdp.send('WebAuthn.addVirtualAuthenticator',{options:{protocol:'ctap2',transport:'internal',hasResidentKey:true,hasUserVerification:true,isUserVerified:true,automaticPresenceSimulation:true}});
  await page.goto(origin+'/login');
  await page.locator('[name=_username]').fill('editor');await page.locator('[name=_password]').fill(state.accounts.editor.password);
  await Promise.all([page.waitForURL('**/desk'),page.getByRole('button',{name:'Sign in',exact:true}).click()]);
  check((await page.title()).includes('Workspace'),'Normal browser form login creates a session');
  await page.goto(state.accounts.editor.passkey_link);
  await page.locator('[data-mode="registration"] [data-approve]').click();
  await page.locator('section.card ul li').waitFor();
  check(await page.locator('section.card ul li').count()===1,'Production registration JavaScript completes with Chromium virtual WebAuthn');
  await page.goto(origin+'/desk');
  const form=page.locator('form[action="/desk/pages"]');
  await form.locator('[name=title]').fill('The neighborhood library opens on Monday');
  await form.locator('[name=body]').fill('Our neighborhood library opens at 9 a.m. on Monday.\n\nThe first week includes a reading room, a repair cafe, and a quiet corner for homework. Everyone is welcome.');
  await Promise.all([page.waitForURL(/\/desk\/pages\/[0-9a-f]{32}$/),form.getByRole('button',{name:'Create draft'}).click()]);
  const id=page.url().split('/').at(-1);
  await page.screenshot({path:resolve(evidence,'01-working-draft.png'),fullPage:true});
  check((await fetch(origin+'/pages/'+id)).status===404,'New working draft is absent from public HTTP');
  await Promise.all([page.waitForURL(/\/approval\/apr_/),page.getByRole('button',{name:'Review saved draft for publication'}).click()]);
  const approval=page.url().match(/apr_[0-9a-f]{32}/)[0];
  check((await fetch(origin+'/pages/'+id)).status===404,'Publication remains private while browser review is pending');
  await page.screenshot({path:resolve(evidence,'02-approval-review.png'),fullPage:true});
  await page.goto(page.url()+'#return=claude-web');
  const reviewUrl=page.url();
  const signBackIn=async()=>{
    await Promise.all([page.waitForURL(url=>url.pathname==='/login'),page.locator('[data-authentication-recovery]').click()]);
    await page.locator('[name=_username]').fill('editor');await page.locator('[name=_password]').fill(state.accounts.editor.password);
    await Promise.all([page.waitForURL(url=>url.pathname===new URL(reviewUrl).pathname),page.getByRole('button',{name:'Sign in',exact:true}).click()]);
    await page.locator('[data-status="pending"]').waitFor();
  };
  await context.clearCookies();
  await page.locator('[data-approve]').click();
  await page.locator('[data-message]').filter({hasText:'Your sign-in expired.'}).waitFor();
  check(completePosts.length===0,'Session loss before options sends no completion or new operation');
  check(!(await page.locator('[data-message]').innerText()).includes('whether your approval was saved'),'A refusal before options does not claim an approval submission');
  check(await page.locator('[data-authentication-recovery]').getAttribute('href')===reviewUrl,'Recovery targets the same existing review including the client return fragment');
  await signBackIn();
  check((await fetch(origin+'/pages/'+id)).status===404,'Signing back in returns to the existing pending request without executing it');
  check(completePosts.length===0,'Sign-in recovery never replays the approval POST automatically');

  const completeUrl=origin+'/approval/'+approval+'/complete';
  await page.route(completeUrl,async route=>{
    await context.clearCookies();
    const headers={...route.request().headers()};delete headers.cookie;
    await route.continue({headers});
  });
  await page.locator('[data-approve]').click();
  await page.locator('[data-message]').filter({hasText:'Your sign-in expired.'}).waitFor();
  await page.unroute(completeUrl);
  check((await page.locator('[data-message]').innerText()).includes('whether your approval was saved'),'Session loss after the authenticator preserves submitted-outcome uncertainty');
  check(completePosts.length===1&&(await fetch(origin+'/pages/'+id)).status===404,'The host refuses the expired completion before publication');
  await signBackIn();
  check(completePosts.length===1,'Returning to the same pending request does not resubmit a credential');
  await page.locator('[data-approve]').click();
  await page.locator('[data-status="completed"]').waitFor();
  check(await page.locator('[data-status="completed"]').count()===1,'Production approval JavaScript completes the exact proposal');
  await page.goto(origin+'/pages/'+id);
  check(await page.locator('.vha-badge').count()===1,'Public HTTP page displays the verified approval badge');
  check((await page.locator('.page-body').innerText()).includes('9 a.m. on Monday'),'Public text matches the reviewed proposal');
  await page.screenshot({path:resolve(evidence,'03-approved-public-page.png'),fullPage:true});
  await page.goto(origin+'/desk/pages/'+id);
  const draft=page.locator(`form[action="/desk/pages/${id}/draft"]`);
  await draft.locator('[name=title]').fill('Next week: extended library hours');
  await draft.locator('[name=body]').fill('This separately saved working draft proposes longer opening hours. It is not public yet.');
  await Promise.all([page.waitForURL('**/desk/pages/'+id),draft.getByRole('button',{name:'Save working draft'}).click()]);
  await page.waitForLoadState('networkidle');
  await page.screenshot({path:resolve(evidence,'04-live-page-with-forward-draft.png'),fullPage:true});
  await page.goto(origin+'/pages/'+id);
  check((await page.locator('.page-body').innerText()).includes('9 a.m. on Monday'),'Saving a forward draft leaves the public snapshot unchanged');
  check(await page.locator('.vha-badge').count()===1,'Saving a forward draft preserves the existing public approval badge');
  check(!(await page.locator('body').innerText()).includes('longer opening hours'),'Private working text is not leaked on the public page');
  await page.setViewportSize({width:390,height:844});await page.goto(origin+'/desk/pages/'+id);
  await page.screenshot({path:resolve(evidence,'05-mobile-workspace.png'),fullPage:true});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile workspace has no horizontal overflow');
  await Promise.all([page.waitForURL(/\/approval\/apr_/),page.getByRole('button',{name:'Review saved draft for publication'}).click()]);
  const lostReviewUrl=page.url();
  const lostApproval=new URL(lostReviewUrl).pathname.split('/').at(-1);
  const lostCompleteUrl=origin+'/approval/'+lostApproval+'/complete';
  let committedResponse=false;
  await page.route(lostCompleteUrl,async route=>{
    const response=await route.fetch();committedResponse=response.ok();
    await route.abort('failed');
  });
  const beforeLost=completePosts.length;
  await page.locator('[data-approve]').click();
  await page.locator('[data-message]').filter({hasText:'whether your approval was saved'}).waitFor();
  await page.unroute(lostCompleteUrl);
  check(committedResponse&&(await (await fetch(origin+'/pages/'+id)).text()).includes('longer opening hours'),'A lost completion response can follow an actually committed publication');
  check(completePosts.length===beforeLost+1,'An uncertain response does not automatically send the approval again');
  await page.reload();await page.locator('[data-status="completed"]').waitFor();
  check(page.url()===lostReviewUrl&&completePosts.length===beforeLost+1,'Reload discovers the same committed request without replaying it');
  check(pageErrors.length===0,'Browser registration, review and publication produce no uncaught JavaScript errors');
  const report={passed:true,browser:'Chromium',physical_authenticator:false,authenticator:'CDP virtual CTAP2 with user verification',checks};
  writeFileSync(resolve(evidence,'browser-results.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
}catch(error){
  writeFileSync(resolve(evidence,'browser-failure.log'),String(error)+'\n'+serverErrors);
  throw error;
}finally{
  if(browser)await browser.close();server.kill();rmSync(runtime,{recursive:true,force:true});
}
